#!/usr/bin/env python3
"""
Phase 1: acoustic coverage of the command-classifier data (tables for README.md).

    python coverage_analysis.py       # reads data/commands_all.csv -> coverage_matrix.csv, coverage_tables.md

For every class: training clips and distinct voices per source (owner recordings, public datasets, Philippine-accent
TTS, cloned FLEURS voices, Piper voices, voice-converted owner recordings), plus where the real (recorded) test
evidence comes from. Then per source: recording condition (device, room, format) and the measured levels before and
after the training augmentation (../../../../data/commands_aug_preview/level_stats.csv, from augment_commands.py).
"""
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]


def main():
    a = pd.read_csv(ROOT / "data/commands_all.csv")
    tr = a[a.split == "train"]
    fam = lambda d: ("owner" if d == "owner_recordings" else "public" if d.startswith("web_") else
                     d.replace("synthetic_", "tts_") if d.startswith("synthetic_") else
                     "converted" if d == "converted_owner" else "fragments" if d.startswith("fragments_") else "reused")
    tr = tr.assign(family=tr.dataset.map(fam))
    clips = pd.crosstab(tr["class"], tr.family)
    voices = tr.groupby(["class", "family"]).speaker.nunique().unstack(fill_value=0)
    m = clips.add_suffix("_clips").join(voices.add_suffix("_voices"))
    real_voices = tr[tr.real & (tr["class"] != "unknown")].groupby("class").speaker.nunique()
    m["real_voices_train"] = real_voices
    te = a[(a.split == "test") & a.real]
    m["real_test_clips"] = te.groupby("class").size()
    m = m.fillna(0).astype(int).sort_values("real_voices_train")
    m.to_csv(HERE / "coverage_matrix.csv")
    lv = pd.read_csv(ROOT / "data/commands_aug_preview/level_stats.csv")
    lvl = lv.groupby(["group", "when"]).median().round(1)
    L = ["# Coverage tables (generated by coverage_analysis.py)", "",
         f"{len(a)} clips; train {len(tr)}, validation {(a.split == 'validation').sum()}, test {(a.split == 'test').sum()}.", "",
         "## Training clips and distinct voices per class and source", "", m.to_markdown(), "",
         "## Levels before and after training augmentation (median; band-pass 150-4000 Hz, 20 ms frames)", "",
         lvl.to_markdown(), ""]
    (HERE / "coverage_tables.md").write_text("\n".join(L))
    print("\n".join(L[:8]))
    print(m[["real_voices_train", "real_test_clips"]].to_string())


if __name__ == "__main__":
    main()
